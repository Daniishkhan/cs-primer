"""A small synthetic web crawl for Lab 1, generated deterministically (no files, no network).

`pages()` returns about 120 `Page` records. Each has raw HTML and the labels the checker
uses to score your pipeline:

    kind     what the generator made: "article", "exact", "light", "medium", "related",
             "spam", "seo", "short", "nonenglish" or "borderline"
    family   pages that are copies of the same article share a family id (else None)
    good     True if a sensible quality filter should keep the page

Pages of one family are the duplicates: an article, a copy that differs only in its
wrapper and capitalisation ("exact"), a copy with two words changed and a byline added
("light"), and a copy with one sentence replaced ("medium"). A "related"
page is NOT a duplicate: it quotes four sentences of another article inside its own text.
An "seo" page is keyword-stuffed but grammatical, so every heuristic rule passes it. A "borderline" page is genuinely good but only 40 words long, which the length rule drops
(the price every filter pays).

You do not edit this file. Changing it changes the answers the checker expects.
"""
import random
from dataclasses import dataclass
from typing import Optional

SEED = 20241


@dataclass(frozen=True)
class Page:
    id: str
    html: str
    kind: str
    family: Optional[str]
    good: bool


