TEMPLATES = [
    "The {a1} {n1} {v1} the {a2} {n2} {p}.",
    "A {a1} {n1} of the {n2} {v1} the {n3} and the {n4}.",
    "Every {n1} that {v1} a {a1} {n2} {p} will have a {a2} {n3}.",
    "Experts say the {a1} {n1} {v1} the {n2} with a {a2} {n3}.",
    "In most years a {a1} {n1} {v1} the {n2} {p}, and the {n3} follows.",
    "To the {n1} the {a1} {n2} {v1} the {n3}, so the {a2} {n4} is easy to explain.",
    "It is the {n1} of the {a1} {n2} that {v1} the {n3} {p}.",
    "Few people notice that the {n1} {v1} a {a1} {n2} with the {a2} {n3}.",
]
PROMOS = ["Subscribe to our newsletter for weekly updates.", "Click here to read more about our partners.",
          "Follow us on social media for more stories like this one."]
COOKIE = "We use cookies to improve your experience. By continuing you accept our cookie policy."
WORD_SWAPS = "quiet=silent careful=cautious steady=stable broad=wide early=prompt simple=plain".split()


def sentence(rng, lex):
    tpl = rng.choice(TEMPLATES)
    fill = {"a1": rng.choice(lex["adj"]), "a2": rng.choice(lex["adj"]), "p": rng.choice(lex["place"]),
            "v1": rng.choice(lex["verb"])}
    for k in ("n1", "n2", "n3", "n4"):
        fill[k] = rng.choice(lex["noun"])
    s = tpl.format(**fill)
    return s[0].upper() + s[1:]


def paragraphs(sentences, rng):
    out, i = [], 0
    while i < len(sentences):
        k = rng.choice([3, 4])
        out.append(" ".join(sentences[i:i + k]))
        i += k
    return out


NAV = ["Home", "News", "About us", "Contact", "Careers", "Sitemap"]


def wrap(title, paras, rng, promo=None, cookie=False, shout=False):
    """Wrap article paragraphs in a realistic page: head, scripts, nav, aside, footer."""
    h1 = title.upper() if shout else title
    nav = "".join(f'<li><a href="/{n.lower().replace(" ", "-")}">{n}</a></li>' for n in rng.sample(NAV, 4))
    body = "\n".join(f"<p>{p}</p>" for p in paras)
    extra = f"<p>{promo}</p>" if promo else ""
    banner = f'<div class="cookie-banner">{COOKIE}</div>' if cookie else ""
    return (f"<!doctype html><html><head><title>{title} | Daily Gazette</title>"
            f"<style>body{{margin:0}} nav li{{display:inline}}</style>"
            f"<script>var tracker = {{id: {rng.randrange(1000, 9999)}}}; window.dataLayer = [];</script></head>"
            f"<body><header><h2>Daily Gazette</h2></header><nav><ul>{nav}</ul></nav>{banner}"
            f"<main><h1>{h1}</h1>\n{body}\n{extra}</main>"
            f"<aside><h3>Related stories</h3><ul><li>Ten facts you missed</li><li>Our best photos</li></ul></aside>"
            f"<footer>Copyright 2024 Daily Gazette. All rights reserved. Terms of use. Privacy policy.</footer>"
            f"</body></html>")


# -- non-article material -----------------------------------------------------------------------------
def spam_page(rng, flavour):
    kw = "cheap watches online best price free shipping buy now discount deals".split()
    if flavour == 0:        # hashtag and ellipsis stuffing
        lines = [" ".join(rng.choice(kw) + ("..." if rng.random() < .5 else "") + " #" + rng.choice(kw)
                          for _ in range(6)) + " ..." for _ in range(12)]
        return "<html><body><div>" + "</div><div>".join(lines) + "</div></body></html>"
    if flavour == 1:        # a wall of bullet points
        items = [f"- {rng.choice(kw)} {rng.choice(kw)} {rng.choice(kw)} {rng.choice(kw)} {rng.choice(kw)}" for _ in range(20)]
        return "<html><body><p>" + "</p><p>".join(items) + "</p></body></html>"
    if flavour == 2:        # one line repeated
        line = "Click here to win a free prize today and claim your reward with us now."
        return "<html><body>" + "".join(f"<p>{line}</p>" for _ in range(8)) + "</body></html>"
    if flavour == 3:        # lorem ipsum
        lorem = ("Lorem ipsum dolor sit amet, consectetur adipiscing elit, sed do eiusmod tempor incididunt ut labore "
                 "et dolore magna aliqua. Ut enim ad minim veniam, quis nostrud exercitation ullamco laboris nisi ut "
                 "aliquip ex ea commodo consequat. Duis aute irure dolor in reprehenderit in voluptate velit esse.")
        return f"<html><body><p>{lorem}</p><p>{lorem}</p></body></html>"
    if flavour == 4:        # hex-and-number gibberish
        words = " ".join(f"{rng.randrange(16**5):05x}{rng.randrange(100)}" for _ in range(90))
        return f"<html><body><p>{words}</p></body></html>"
    # flavour 5: a dump of URLs, mean word length far above ten
    urls = " ".join(f"https://example-{rng.randrange(99)}.com/products/category-{rng.randrange(99)}/item-{rng.randrange(9999)}"
                    for _ in range(25))
    return f"<html><body><p>{urls}</p></body></html>"


def seo_page(rng):
    """Keyword-stuffed but grammatical English: every rule passes, a human would still bin it."""
    kw = rng.choice(["buy cheap watches online", "find the best price on used cars", "get free shipping on running shoes"])
    tpl = ["You can {kw} today in {c} and the prices will have you coming back for more.",
           "Shoppers who {kw} with us in {c} get a great deal and the best service of any store.",
           "To {kw} in {c} is easy, and we promise the offer that you have been looking for.",
           "Many customers in {c} say that they {kw} here because the staff have the lowest prices."]
    cities = rng.sample(["Leeds", "Austin", "Lyon", "Perth", "Turin", "Osaka", "Quito", "Bergen", "Cork", "Dakar"], 8)
    body = [rng.choice(tpl).format(kw=kw, c=c) for c in cities]
    return "<html><body><main><h1>Best deals</h1><p>" + "</p><p>".join(body) + "</p></main></body></html>"


def short_page(rng):
    stubs = ["Page not found. Please check the address and try again.", "Coming soon. Our new site is under construction.",
             "Thank you for your order. A receipt has been sent to you.", "Login required. Please sign in to view this page.",
             "Sorry, this item is no longer available in your region."]
    return f"<html><body><nav><a href='/'>Home</a></nav><p>{rng.choice(stubs)}</p></body></html>"


def non_english_page(rng, lang):
    es = dict(s="el gato duerme cerca de la ventana mientras la lluvia cae sobre los techos de la ciudad vieja".split(),
              extra="los vecinos hablan de la fiesta del barrio y de las calles llenas de luz cada tarde del verano".split())
    de = dict(s="der Hund schläft neben dem Fenster während der Regen auf die Dächer der alten Stadt fällt".split(),
              extra="die Nachbarn sprechen über das Fest im Viertel und über die hellen Strassen jeden Abend im Sommer".split())
    d = es if lang == "es" else de
    out = []
    for _ in range(10):
        w = d["s"] + d["extra"]
        rng.shuffle(w)
        out.append(" ".join(w[:rng.randint(14, 20)]).capitalize() + ".")
    return "<html><body><p>" + "</p><p>".join(out) + "</p></body></html>"


def borderline_page(rng):
    lex = TOPICS[rng.choice(sorted(TOPICS))]
    sents = [sentence(rng, lex) for _ in range(3)]
    while len(" ".join(sents).split()) > 42:
        sents.pop()
    return "<html><body><main><h1>Short note</h1><p>" + " ".join(sents) + "</p></main></body></html>"


# -- the crawl ---------------------------------------------------------------------------------------
def build():
    rng = random.Random(SEED)
    raw = []                                   # (html, kind, family, good)
    topics = sorted(TOPICS)
    articles = []
    for i in range(40):
        topic = topics[i % len(topics)]
        lex = TOPICS[topic]
        sents = [sentence(rng, lex) for _ in range(rng.randint(10, 12))]
        title = f"{topic.capitalize()} report {i + 1} &amp; outlook"
        articles.append((f"F{i:02d}", topic, title, sents))

    for fam, topic, title, sents in articles:
        lex = TOPICS[topic]
        promo = rng.choice(PROMOS) if rng.random() < .6 else None
        raw.append((wrap(title, paragraphs(sents, rng), rng, promo, rng.random() < .3), "article", fam, True))
    for k, (fam, topic, title, sents) in enumerate(articles):
        lex = TOPICS[topic]
        if k % 3 == 0:        # exact: same words, different wrapper, headline in capitals, new promo
            raw.append((wrap(title, paragraphs(sents, rng), rng, rng.choice(PROMOS), rng.random() < .5, shout=True),
                        "exact", fam, True))
        if k % 3 == 1:        # light: two word swaps and a byline
            s2 = list(sents)
            for j in rng.sample(range(len(s2)), 2):
                for pair in WORD_SWAPS:
                    a, b = pair.split("=")
                    if f" {a} " in s2[j]:
                        s2[j] = s2[j].replace(f" {a} ", f" {b} ", 1)
                        break
                else:
                    w = s2[j].split()
                    w[2] = rng.choice(lex["adj"])
                    s2[j] = " ".join(w)
            paras = ["By the staff writer, 12 March 2025."] + paragraphs(s2, rng)
            raw.append((wrap(title, paras, rng, None, False), "light", fam, True))
        if k % 4 == 2:        # medium: one sentence replaced
            s2 = list(sents)
            s2[rng.randrange(len(s2))] = sentence(rng, lex)
            raw.append((wrap(title, paragraphs(s2, rng), rng, rng.choice(PROMOS), False), "medium", fam, True))
    for k in range(6):        # related: new article that quotes four sentences of another
        fam, topic, title, sents = articles[(k * 5) % len(articles)]
        lex = TOPICS[topic]
        own = [sentence(rng, lex) for _ in range(8)]
        for q in rng.sample(sents, 4):
            own.insert(rng.randrange(len(own) + 1), q)
        raw.append((wrap(f"{topic.capitalize()} explained {k + 1}", paragraphs(own, rng), rng, None, False), "related", None, True))
    for k in range(12):
        raw.append((spam_page(rng, k % 6), "spam", None, False))
    for k in range(4):
        raw.append((seo_page(rng), "seo", None, False))
    for k in range(8):
        raw.append((short_page(rng), "short", None, False))
    for k in range(8):
        raw.append((non_english_page(rng, "es" if k % 2 else "de"), "nonenglish", None, False))
    for k in range(3):
        raw.append((borderline_page(rng), "borderline", None, True))
    rng.shuffle(raw)
    return [Page(f"d{i:03d}", h, kind, fam, good) for i, (h, kind, fam, good) in enumerate(raw)]


_CACHE = []


def pages():
    """The crawl, in a fixed order with ids d000, d001, ..."""
    if not _CACHE:
        _CACHE.extend(build())
    return list(_CACHE)


def gold_pairs(ids=None):
    """Every unordered pair of pages in the same family: the true duplicate pairs.

    If `ids` is given, only pairs whose both members are in `ids` are returned
    (use it to score a pipeline on the pages that survived filtering).
    """
    by = {}
    for p in pages():
        if p.family and (ids is None or p.id in ids):
            by.setdefault(p.family, []).append(p.id)
    return {(a, b) for ms in by.values() for i, a in enumerate(sorted(ms)) for b in sorted(ms)[i + 1:]}


if __name__ == "__main__":
    from collections import Counter
    ps = pages()
    print(len(ps), "pages:", dict(Counter(p.kind for p in ps)))
    print("gold duplicate pairs:", len(gold_pairs()))
