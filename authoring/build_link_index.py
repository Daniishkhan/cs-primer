"""Write authoring/link-index.md from the catalog: every page with its path.

    python3 authoring/build_link_index.py

Authors take every cross-link from this file (guide section 1), so re-run it
after any catalog change. Pages that do not exist yet are listed too, marked
"(not written yet)": linking to them is allowed while a course is built.
"""
import json
import os
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
JS = ("global.window={};require(process.argv[1]);console.log(JSON.stringify({courses:window.CS_COURSES,"
      "artifacts:window.CS_ARTIFACTS||[]}))")
KINDS = [("labs", "labs", "Lab"), ("workbenches", "workbench", "Workbench"),
         ("cases", "cases", "Case"), ("studios", "studios", "Studio")]


def main():
    data = json.loads(subprocess.run(["node", "-e", JS, os.path.join(ROOT, "assets/js/catalog.js")],
                                     capture_output=True, text=True, check=True).stdout)
    paths = {}
    out = ["# Link index (generated by authoring/build_link_index.py from assets/js/catalog.js; do not edit)", "",
           "Paths are from the site root. From a page in `<course>/chapters/`, link to another page as "
           "`../../<path>` (same course: `../chapters/…`, `../labs/…`). Ids in the form `course:chapter` "
           "(`oe:15`) are what `related` and the artifact lists use.", ""]

    def exists(p):
        return "" if os.path.exists(os.path.join(ROOT, p)) else " (not written yet)"

    for c in data["courses"]:
        out.append("## %s · %s  (id \"%s\", folder %s/)" % (c["num"], c["title"], c["id"], c["dir"]))
        out.append("")
        out.append("- %s/index.html · course roadmap%s" % (c["dir"], exists(c["dir"] + "/index.html")))
        if c.get("tools"):
            out.append("- %s/toolbox.html · toolbox%s" % (c["dir"], exists(c["dir"] + "/toolbox.html")))
        for p, part in enumerate(c["parts"]):
            out.append("")
            out.append("Part %d: %s" % (p, part["title"]))
            for ch in c["chapters"]:
                if ch["part"] != p:
                    continue
                path = "%s/chapters/%s" % (c["dir"], ch["file"])
                paths["%s:%s" % (c["id"], ch["id"])] = path
                out.append("- %s · ch %s · %s · %s: %s%s" % (path, ch["id"], ch["depth"], ch["title"], ch["blurb"], exists(path)))
        for key, folder, noun in KINDS:
            items = c.get(key) or []
            if not items:
                continue
            out.append("")
            out.append(noun + "s")
            for x in items:
                path = "%s/%s/%s" % (c["dir"], folder, x["file"])
                paths["%s:%s" % (c["id"], x["id"])] = path
                out.append("- %s · %s · %s %s: %s%s" % (path, x["id"], noun, x["id"][1:], x["title"], exists(path)))
        out.append("")
    out.append("## The artifact track (CS_ARTIFACTS)")
    out.append("")
    for a in data["artifacts"]:
        out.append("### Artifact %d: %s" % (a["num"], a["title"]))
        for k, label in (("warmup", "Week-one warm-up"), ("before", "Read before starting"),
                         ("while", "Open while building"), ("build", "Build it with")):
            ids = a.get(k) or []
            if ids:
                out.append("%s: %s" % (label, ", ".join("%s (%s)" % (i, paths.get(i, "?")) for i in ids)))
        out.append("")
    open(os.path.join(ROOT, "authoring/link-index.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
    print("authoring/link-index.md: %d pages" % len(paths))


if __name__ == "__main__":
    main()
