"""Build the data behind the Review page and site search, from the pages.

    python3 authoring/build_study.py

Writes assets/js/review-data.js (every quiz question on every page, with its
answer, explanation and source page) and assets/js/search-data.js (every
page title, blurb and section heading, with links). Re-run after adding or
editing pages; both files are generated, never edited by hand.
"""
import hashlib
import html
import json
import os
import re
import subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KINDS = (("chapters", "chapter"), ("labs", "lab"), ("cases", "case"), ("studios", "studio"),
         ("workbench", "workbench"))
LABEL = {"lab": "Lab", "case": "Case", "studio": "Studio", "workbench": "Workbench"}


def catalog():
    js = ("global.window={};require(%r);console.log(JSON.stringify(window.CS_COURSES.map(c=>({id:c.id,dir:c.dir,"
          "title:c.title,num:c.num||null,track:c.track||null,items:[].concat("
          "c.chapters.map(x=>({k:'chapter',id:x.id,file:x.file,title:x.title,blurb:x.blurb})),"
          "c.labs.map(x=>({k:'lab',id:x.id,file:x.file,title:x.title,blurb:x.blurb})),"
          "c.cases.map(x=>({k:'case',id:x.id,file:x.file,title:x.title,blurb:x.blurb})),"
          "(c.studios||[]).map(x=>({k:'studio',id:x.id,file:x.file,title:x.title,blurb:x.blurb})),"
          "(c.workbenches||[]).map(x=>({k:'workbench',id:x.id,file:x.file,title:x.title,blurb:x.blurb})))}))))"
          ) % os.path.join(ROOT, "assets/js/catalog.js")
    return json.loads(subprocess.check_output(["node", "-e", js]))


def text(fragment):
    t = re.sub(r"<[^>]+>", "", fragment)
    return re.sub(r"\s+", " ", html.unescape(t)).strip()


def slug(s):  # same as main.js
    return re.sub(r"^-|-$", "", re.sub(r"[^a-z0-9]+", "-", s.lower()))


def label(item):
    if item["k"] == "chapter":
        return f'{int(item["id"])}. {item["title"]}'
    return f'{LABEL[item["k"]]} {int(item["id"][1:])}: {item["title"]}'


def questions(src):
    m = re.search(r'<section class="quiz">(.*?)</section>', src, re.S)
    if not m:
        return []
    out = []
    for block in re.split(r'(?=<div class="q" )', m.group(1))[1:]:
        ans = re.match(r'<div class="q" data-answer="(\d+)"', block)
        qt = re.search(r'<p class="q-text">(.*?)</p>', block, re.S)
        opts = re.search(r'<ol class="q-options">(.*?)</ol>', block, re.S)
        ex = re.search(r'<div class="q-explain">(.*?)</div>', block, re.S)
        if not (ans and qt and opts):
            continue
        options = [o.strip() for o in re.findall(r"<li>(.*?)</li>", opts.group(1), re.S)]
        a = int(ans.group(1))
        if not 0 <= a < len(options):
            continue
        out.append({"q": qt.group(1).strip(), "o": options, "a": a, "x": (ex.group(1).strip() if ex else "")})
    return out


def main():
    review, search = [], []
    for co in catalog():
        course_label = (co["num"] + " " if co["num"] else "") + co["title"]
        for item in co["items"]:
            folder = dict((k, d) for d, k in KINDS)[item["k"]]
            rel = f'{co["dir"]}/{folder}/{item["file"]}'
            path = os.path.join(ROOT, rel)
            if not os.path.exists(path):
                continue
            src = open(path, encoding="utf-8").read()
            page = label(item)
            search.append({"t": page, "s": item["blurb"], "h": rel, "c": course_label, "k": item["k"]})
            body = src[src.find('<article class="prose">'):]
            for h in re.findall(r"\n<h2[^>]*>(.*?)</h2>", body, re.S):
                name = text(h)
                if name and name not in ("Further reading", "Check your understanding", "Sources"):
                    search.append({"t": name, "s": page, "h": rel + "#" + slug(name), "c": course_label, "k": "section"})
            for n, q in enumerate(questions(src)):
                qid = hashlib.sha1(f'{rel}|{text(q["q"])}'.encode()).hexdigest()[:12]
                review.append({"id": qid, "c": co["id"], "i": item["id"], "k": item["k"], "p": page,
                               "h": rel, "n": n, **q})
    for name, var, data in (("review-data.js", "CS_REVIEW", review), ("search-data.js", "CS_SEARCH", search)):
        with open(os.path.join(ROOT, "assets/js", name), "w", encoding="utf-8") as f:
            f.write(f"/* Generated by authoring/build_study.py from the pages. Do not edit. */\n")
            f.write(f"window.{var} = {json.dumps(data, ensure_ascii=False, separators=(',', ':'))};\n")
        print(f"assets/js/{name}: {len(data)} entries, {os.path.getsize(os.path.join(ROOT, 'assets/js', name)) // 1024} KB")


if __name__ == "__main__":
    main()
